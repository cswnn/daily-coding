SELECT
    R.FOOD_TYPE
    , R.REST_ID
    , R.REST_NAME
    , R.FAVORITES
FROM
    # REST_INFO
    (
        SELECT      *, RANK() OVER(PARTITION BY FOOD_TYPE ORDER BY FAVORITES DESC) AS RNK
        FROM        REST_INFO
        ORDER BY    FAVORITES DESC
    ) AS R
WHERE
    RNK = 1
# GROUP BY
#     FOOD_TYPE
# HAVING
#     FAVORITES = MAX(FAVORITES)
ORDER BY
    FOOD_TYPE DESC